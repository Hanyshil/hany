def thin_border():
    s = Side(style="thin")
    return Border(left=s, right=s, top=s, bottom=s)

def set_col_width(ws, col, w):
    ws.column_dimensions[get_column_letter(col)].width = w

def hdr(ws, row, col, text, fill=None, font=None, align_h="center"):
    c = ws.cell(row=row, column=col, value=text)
    if fill: c.fill = fill
    if font: c.font = font
    c.alignment = Alignment(horizontal=align_h, vertical="center", wrap_text=True)
    c.border = thin_border()
    return c

def cell(ws, row, col, text, fill=None, font=None, align_h="right"):
    c = ws.cell(row=row, column=col, value=text)
    if fill: c.fill = fill
    c.font = font or NORMAL_FONT
    c.alignment = Alignment(horizontal=align_h, vertical="top", wrap_text=True)
    c.border = thin_border()
    return c

