def cs(ws, r, c, val, bold=False, sz=10, fc="000000", bg=None,
       wrap=False, ah="center", av="center", mr=None):
    cell = ws.cell(row=r, column=c, value=val)
    cell.font = Font(bold=bold, size=sz, color=fc,
                     name="David" if rtl(str(val)) else "Calibri")
    if bg: cell.fill = PatternFill("solid", fgColor=bg)
    cell.alignment = Alignment(horizontal=ah, vertical=av, wrap_text=wrap)
    t = Side(style="thin", color="BDBDBD")
    cell.border = Border(left=t, right=t, top=t, bottom=t)
    if mr: ws.merge_cells(start_row=r, start_column=c, end_row=r, end_column=mr)
    return cell

